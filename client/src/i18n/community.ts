export function communityError(message: string, locale: Locale) {
  const t = communityCopy[locale];
  if (message.includes("groups_invalid_link")) return t.invalid;
  const errors: Record<string, string> = {
    groups_duplicate: t.duplicate,
    groups_limit: t.limit,
    groups_changed: t.changed,
    groups_verify_email: t.verify,
    groups_evidence_required: t.evidenceError,
    groups_provider_unavailable: t.evidenceError,
    groups_review_required: t.reviewRequired,
    groups_missing: t.unavailable,
    member_rate_limited: t.rate,
    member_sign_in_required: t.signIn,
    member_reauthenticate: t.signIn,
    member_invalid_credentials: t.signIn,
  };
  return errors[message] ?? t.error;
}
