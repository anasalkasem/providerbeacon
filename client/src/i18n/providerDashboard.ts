export function dashboardText(locale: Locale) {
  const index = ["en", "ar", "es", "hi", "zh"].indexOf(locale);
  return Object.fromEntries(
    Object.entries(labels).map(([key, values]) => [
      key,
      values[index < 0 ? 0 : index],
    ])
  ) as Record<keyof typeof labels, string>;
}
