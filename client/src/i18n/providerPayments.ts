export function paymentText(locale: Locale) {
  const index = { en: 0, ar: 1, es: 2, hi: 3, zh: 4 }[locale];
  return Object.fromEntries(
    Object.entries(strings).map(([key, values]) => [key, values[index]])
  ) as Record<keyof typeof strings, string>;
}
export function paymentError(message: string, locale: Locale) {
  const t = paymentText(locale);
  return (
    (
      {
        payment_configuration: t.configuration,
        payment_webhook_configuration: t.paypalSetup,
        payment_open_payment: t.open,
        payment_suspended: t.suspended,
        payment_unavailable: t.unavailable,
      } as Record<string, string>
    )[message] ?? t.error
  );
}
