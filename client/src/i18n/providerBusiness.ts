type BusinessText = Record<keyof typeof strings, string>;
const localeIndex: Record<Locale, number> = {
  en: 0,
  ar: 1,
  es: 2,
  hi: 3,
  zh: 4,
};
export function businessText(locale: Locale): BusinessText {
  return Object.fromEntries(
    Object.entries(strings).map(([key, translations]) => [
      key,
      translations[localeIndex[locale]],
    ])
  ) as BusinessText;
}
export function businessError(message: string, locale: Locale) {
  const t = businessText(locale);
  const errors: Record<string, string> = {
    business_subscription_required: t.locked,
    business_verify_email: t.verify,
    business_owner_required: t.ownerChanged,
    business_changed: t.changed,
    business_claimed: t.claimed,
    business_already_owner: t.claimed,
    business_claim_expired: t.expiredCode,
    business_proof_domain: t.claimHelp,
    business_destination_domain: t.wrongDomain,
    business_promotion_limit: t.limit,
    business_invalid_dates: t.invalidDates,
    business_pricing_start_fixed: providerPricingText(locale).startFixed,
  };
  return errors[message] ?? t.failed;
}
