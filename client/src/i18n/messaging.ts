export function messagingError(locale: Locale, error: unknown) {
  const t = messagingCopy[locale],
    code = error instanceof Error ? error.message : "";
  const map: Record<string, string> = {
    messaging_limit: t.limit,
    messaging_closed: t.closed,
    messaging_agent_offline: t.agentOffline,
    messaging_agent_full: t.agentFull,
    messaging_already_assigned: t.claimed,
    messaging_recipient: t.recipientGone,
    messaging_claim_first: t.claimFirst,
    messaging_session: t.session,
    messaging_missing: t.conversationError,
  };
  return map[code] ?? t.error;
}
